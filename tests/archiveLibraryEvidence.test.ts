import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import AdmZip from 'adm-zip';
import sharp from 'sharp';
import {buildArchiveLibraryEvidence} from '../src/server/archiveLibraryEvidence';
import {buildSyntheticPms} from './helpers';

test('separate library records preserve bundle provenance, check all byte versions and verify the selected file on reread',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'sms-library-evidence-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const install=path.join(root,'one'), packs=path.join(root,'packs');
  const bytes=Buffer.from(buildSyntheticPms({props:1,scenery:['Original.png'],propSizes:[{width:5,height:4}]}));
  const red=await sharp({create:{width:5,height:4,channels:4,background:'#a23'}}).png().toBuffer();
  const blue=await sharp({create:{width:5,height:4,channels:4,background:'#23a'}}).png().toBuffer();
  for(const dir of ['maps','scenery-gfx','screens','bots']) await fs.mkdir(path.join(install,dir),{recursive:true});
  await fs.mkdir(packs);
  await fs.writeFile(path.join(install,'maps','Arena.pms'),bytes);
  const sprite=path.join(install,'scenery-gfx','Original.png');
  await fs.writeFile(sprite,red);
  await fs.writeFile(path.join(install,'screens','Original.png'),blue);
  await fs.writeFile(path.join(install,'bots','probe.pms'),bytes);
  const one=await buildArchiveLibraryEvidence([install,path.join(install,'maps')]);
  t.after(()=>one.dispose());
  assert.equal(one.assets.length,1);
  assert.equal(one.maps.length,1);
  assert.equal(one.find(one.maps[0],'scenery','Original.png',{width:5,height:4,date:0}),undefined);
  assert.deepEqual(await one.read(one.assets[0]),red);
  assert.equal(one.find(one.maps[0],'scenery','Original.png',{width:6,height:4,date:0}),undefined);
  assert.equal(one.find({...one.maps[0],sha256:'other map'},'scenery','Original.png',{width:5,height:4,date:0}),undefined);
  const zip=new AdmZip();
  zip.addFile('maps/RenamedMap.pms',bytes); zip.addFile('scenery-gfx/Original.png',blue);
  zip.writeZip(path.join(packs,'version.zip'));
  const dedicated=await buildArchiveLibraryEvidence([packs],{tempDir:root});
  t.after(()=>dedicated.dispose());
  const ok=dedicated.find(one.maps[0],'scenery','Original.png',{width:5,height:4,date:0})!;
  assert.ok(ok.reason.includes(one.maps[0].sha256));
  assert.deepEqual(await dedicated.read(ok.asset),blue);
  const both=await buildArchiveLibraryEvidence([install,packs],{tempDir:root});
  t.after(()=>both.dispose());
  assert.equal(both.find(one.maps[0],'scenery','Original.png'),undefined);
  const packed=both.assets.find(f=>f.path.includes('!/'))!;
  assert.deepEqual(await both.read(packed),blue);
  await fs.writeFile(sprite,blue);
  await assert.rejects(()=>one.read(one.assets[0]),/changed/);
});

test('an incomplete graphics package cannot supply an apparently valid preceding map', async t=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'sms-library-partial-'));
  t.after(()=>fs.rm(temp,{recursive:true,force:true}));
  const zip=new AdmZip();
  zip.addFile('maps/A.pms',Buffer.from(buildSyntheticPms({})));
  zip.addFile('scenery-gfx/end.png',await sharp({create:{width:3,height:2,channels:3,background:'#245'}}).png().toBuffer());
  const data=zip.toBuffer(), signature=Buffer.from([0x50,0x4b,1,2]);
  const first=data.indexOf(signature), second=data.indexOf(signature,first+4);
  assert.ok(second>first);
  data.writeUInt32LE(0,second+16);
  const p=path.join(temp,'partial.zip');
  await fs.writeFile(p,data);
  const issues:string[]=[];
  const library=await buildArchiveLibraryEvidence([p],{tempDir:temp,onIssue:i=>issues.push(i.reason)});
  t.after(()=>library.dispose());
  assert.ok(issues.some(message=>message.includes('CRC')));
  assert.deepEqual(library.maps,[]);
  assert.deepEqual(library.assets,[]);
});

test('a selected multi-map release confirms an exact PMS and a dependency in sibling game folders',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'sms-map-pack-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const zip=new AdmZip();
  const map=Buffer.from(buildSyntheticPms({props:1,scenery:['Logo.png'],propSizes:[{width:5,height:4}]}));
  const image=await sharp({create:{width:5,height:4,channels:4,background:'#345'}}).png().toBuffer();
  zip.addFile('Release/maps/First.pms',map);
  zip.addFile('Release/maps/Other.pms',Buffer.from(buildSyntheticPms({})));
  zip.addFile('Release/scenery-gfx/Logo.png',image);
  zip.addFile('Release/cover.png',image);
  const pack=path.join(root,'pack.zip');
  zip.writeZip(pack);
  const catalog=await buildArchiveLibraryEvidence([root,pack]);
  t.after(()=>catalog.dispose());
  const first=catalog.maps.find(row=>row.name==='First.pms')!;
  const dims={width:5,height:4,date:0};
  const match=catalog.find(first,'scenery','Logo.png',dims);
  assert.match(match?.reason??'',/selected multi-map release/);
  assert.deepEqual(await catalog.read(match!.asset),image);
  assert.equal(catalog.find(first,'scenery','cover.png',dims),undefined);
  assert.equal(catalog.find({...first,sha256:'different'},'scenery','Logo.png',dims),undefined);
  const directory=await buildArchiveLibraryEvidence([root]);
  t.after(()=>directory.dispose());
  assert.equal(directory.find(first,'scenery','Logo.png',dims),undefined);
});
